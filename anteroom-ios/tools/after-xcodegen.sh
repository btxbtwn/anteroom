#!/bin/bash
# Runs after `xcodegen` (project.yml's postGenCommand), in this folder.
# 1. Pins every Swift package to the versions in Config/Package.resolved.
# 2. Sets the app version from anteroom/VERSION, the version the whole
#    product ships as, through Config/Version.xcconfig (not tracked).
# 3. Writes Sources/Info-Debug.plist from Sources/Info.plist with
#    NSAllowsLocalNetworking enabled for Debug-only local sandbox runs.
set -euo pipefail
cd "$(dirname "$0")/.."
resolved_dir=Anteroom.xcodeproj/project.xcworkspace/xcshareddata/swiftpm
mkdir -p "$resolved_dir"
cp Config/Package.resolved "$resolved_dir/Package.resolved"
version="$(tr -d '[:space:]' < ../anteroom/VERSION)"
if [[ ! "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "anteroom/VERSION is not a version: $version" >&2
  exit 1
fi
printf '// Written by tools/after-xcodegen.sh from anteroom/VERSION.\nMARKETING_VERSION = %s\n' "$version" > Config/Version.xcconfig
if [[ ! -f Sources/Info.plist ]]; then
  echo "Sources/Info.plist was not generated by xcodegen." >&2
  exit 1
fi
python3 - <<'PY'
import plistlib
from pathlib import Path

info = plistlib.loads(Path("Sources/Info.plist").read_bytes())
ats = dict(info.get("NSAppTransportSecurity", {}))
ats["NSAllowsLocalNetworking"] = True
info["NSAppTransportSecurity"] = ats
Path("Sources/Info-Debug.plist").write_bytes(plistlib.dumps(info, fmt=plistlib.FMT_XML))
PY
